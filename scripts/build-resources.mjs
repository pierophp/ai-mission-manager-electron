import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pstackRoot = path.join(root, "agents/pstack");
const productSkillsRoot = path.join(root, "agents/skills");
const hookScript = fs.readFileSync(
  path.join(root, "src/main/resources/agent-state-hook.sh"),
  "utf8",
);
const files = [];
function visit(directory) {
  for (const entry of fs
    .readdirSync(directory, { withFileTypes: true })
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
    const absolute = path.join(directory, entry.name);
    if (entry.isSymbolicLink()) continue;
    if (entry.isDirectory()) visit(absolute);
    else if (entry.isFile()) files.push(absolute);
  }
}
visit(pstackRoot);
files.sort((a, b) => {
  const left = path.relative(pstackRoot, a).split(path.sep).join("/");
  const right = path.relative(pstackRoot, b).split(path.sep).join("/");
  return left < right ? -1 : left > right ? 1 : 0;
});
const patches = fs.readFileSync(path.join(pstackRoot, "PATCHES.md"), "utf8");
const source = patches.split(/\r?\n/).find((line) => line.startsWith("Upstream source:"));
const version = source?.match(/version `([^`]+)`/)?.[1];
const upstreamCommit = source?.match(/commit `([^`]+)`/)?.[1];
if (!version || !upstreamCommit) throw new Error("Missing pstack upstream metadata in PATCHES.md");
const hash = crypto.createHash("sha256");
const entries = files.map((absolute) => {
  const relative = path.relative(pstackRoot, absolute).split(path.sep).join("/");
  const contents = fs.readFileSync(absolute);
  const executable = process.platform !== "win32" && (fs.statSync(absolute).mode & 0o111) !== 0;
  hash.update(Buffer.from(relative));
  hash.update(Buffer.from([0]));
  const size = Buffer.alloc(8);
  size.writeBigUInt64BE(BigInt(contents.length));
  hash.update(size);
  hash.update(contents);
  hash.update(Buffer.from([executable ? 1 : 0]));
  return { path: relative, base64: contents.toString("base64"), executable };
});
const treeHash = hash.digest("hex");
const skills = {};
for (const name of ["grilling", "to-spec", "to-tickets", "implement"]) {
  skills[name] = fs.readFileSync(path.join(productSkillsRoot, name, "SKILL.md"), "utf8");
}
const out = path.join(root, "src/main/generated-resources.ts");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  `// Generated by scripts/build-resources.mjs.\nexport const pstackManifest = ${JSON.stringify({ version, upstreamCommit, treeHash, files: entries })} as const;\nexport const productSkills = ${JSON.stringify(skills)} as const;\nexport const AGENT_STATE_HOOK_SCRIPT = ${JSON.stringify(hookScript)};\n`,
);
fs.writeFileSync(
  path.join(root, "src/main/pstack-manifest.json"),
  `${JSON.stringify({ version, upstreamCommit, treeHash }, null, 2)}\n`,
);
console.log(`Generated pstack ${version} (${treeHash}) and product skill resources`);
